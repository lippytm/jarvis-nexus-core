"""Bounded offline AI-tool scaffold generator. Does not run generated code."""
from dataclasses import dataclass
from hashlib import sha256
from types import MappingProxyType
import re

_HEADER = 'def run(payload):\n    """Template generated by Jarvis sandbox."""\n'
# Builder and evaluator share a fixed catalog; callers cannot edit its baseline.
TEMPLATE_SOURCES = MappingProxyType({
    "validation_tool": _HEADER + "    return {'valid': isinstance(payload, dict)}\n",
    "report_tool": _HEADER + "    return {'summary': 'synthetic-only', 'count': len(payload) if isinstance(payload, list) else 0}\n",
    # Reconciled from the separately recovered v1.0 package, never executed.
    "consent_check": "def run(record):\n    return isinstance(record, dict) and 'consent' in record and record['consent'] is True\n",
    "synthetic_count": "def run(records):\n    return len(records) if isinstance(records, list) else 0\n",
})
ALLOWED_TEMPLATES = frozenset(TEMPLATE_SOURCES)

@dataclass(frozen=True)
class ToolSpec:
    name: str
    template: str
    description: str

def generate_candidate(spec: ToolSpec):
    if not isinstance(spec, ToolSpec):
        raise ValueError("invalid tool specification")
    if not isinstance(spec.name, str) or not re.fullmatch(r"[a-z][a-z0-9_]{2,39}", spec.name):
        raise ValueError("invalid tool name")
    if not isinstance(spec.template, str) or spec.template not in ALLOWED_TEMPLATES:
        raise ValueError("template not allowlisted")
    if not isinstance(spec.description, str) or len(spec.description) > 300:
        raise ValueError("description too long")
    # User descriptions never enter executable source.
    body = TEMPLATE_SOURCES[spec.template]
    return {"filename": spec.name + ".py", "content": body,
            "sha256": sha256(body.encode("utf-8")).hexdigest(),
            "template": spec.template,
            "status": "generated_not_executed"}
