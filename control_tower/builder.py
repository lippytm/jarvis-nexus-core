"""Bounded offline AI-tool scaffold generator. Does not run generated code."""
from dataclasses import dataclass
from hashlib import sha256
import re

ALLOWED_TEMPLATES = {"validation_tool", "report_tool"}

@dataclass(frozen=True)
class ToolSpec:
    name: str
    template: str
    description: str

def generate_candidate(spec: ToolSpec):
    if not re.fullmatch(r"[a-z][a-z0-9_]{2,39}", spec.name):
        raise ValueError("invalid tool name")
    if spec.template not in ALLOWED_TEMPLATES:
        raise ValueError("template not allowlisted")
    if len(spec.description) > 300:
        raise ValueError("description too long")
    # Description is represented as a Python string literal to prevent code injection.
    body = (
        "def run(payload):\n"
        + "    \"\"\"" + "Template generated by Jarvis sandbox." + "\"\"\"\n"
        + ("    return {'valid': isinstance(payload, dict)}\n" if spec.template == "validation_tool"
           else "    return {'summary': 'synthetic-only', 'count': len(payload) if isinstance(payload, list) else 0}\n")
    )
    return {"filename": spec.name + ".py", "content": body,
            "sha256": sha256(body.encode("utf-8")).hexdigest(),
            "status": "generated_not_executed"}
